export function resolveInstitutionFromEmail(email: string): InstitutionMeta {
  const clean = email.trim().toLowerCase();
  const domainPart = clean.includes('@') ? clean.split('@')[1] : clean;

  const found = KNOWN_INSTITUTIONS.find(
    (inst) => domainPart === inst.domain || domainPart.endsWith('.' + inst.domain)
  );

  if (found) return found;

  // Custom university fallback
  const schoolName = domainPart
    .replace(/\.edu$/, '')
    .replace(/^canvas\./, '')
    .split('.')[0]
    .replace(/-/g, ' ')
    .replace(/\b\w/g, (l) => l.toUpperCase());

  return {
    domain: domainPart,
    name: `${schoolName} University`,
    canvasUrl: `https://canvas.${domainPart}`,
    state: 'US',
    accentColor: '#2563eb',
  };
}

